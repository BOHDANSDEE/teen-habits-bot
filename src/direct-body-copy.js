function makeStates(pairs) {
  if (pairs.length !== 20 || STATE_DETAILS.length !== 25) {
    throw new Error("Direct state pool requires 20 body pairs × 25 one-sentence variants");
  }
  return pairs.flatMap(([state]) =>
    STATE_DETAILS.map((detail) => `Ти відчуваєш ${state} ${detail}.`)
  );
}

function makeResults(pairs) {
  if (pairs.length !== 20 || RESULT_DETAILS.length !== 25) {
    throw new Error("Direct result pool requires 20 body pairs × 25 one-sentence variants");
  }
  return pairs.flatMap(([, result]) =>
    RESULT_DETAILS.map((detail) => `Тепер ти відчуваєш ${result} ${detail}.`)
  );
}

export const PRIMARY_BODY_STATES = Object.fromEntries(
  Object.entries(PRIMARY_BODY_PAIRS).map(([themeKey, pairs]) => [themeKey, makeStates(pairs)])
);

export const PRIMARY_BODY_RESULTS = Object.fromEntries(
  Object.entries(PRIMARY_BODY_PAIRS).map(([themeKey, pairs]) => [themeKey, makeResults(pairs)])
);

export const GENERIC_DIRECT_STATES = makeStates(GENERIC_BODY_PAIRS);
export const GENERIC_DIRECT_RESULTS = makeResults(GENERIC_BODY_PAIRS);

for (const [name, pool] of Object.entries({
  ...Object.fromEntries(Object.entries(PRIMARY_BODY_STATES).map(([key, value]) => [`state:${key}`, value])),
  ...Object.fromEntries(Object.entries(PRIMARY_BODY_RESULTS).map(([key, value]) => [`result:${key}`, value])),
  genericStates: GENERIC_DIRECT_STATES,
  genericResults: GENERIC_DIRECT_RESULTS
})) {
  if (pool.length !== POOL_SIZE || new Set(pool).size !== POOL_SIZE) {
    throw new Error(`${name} must contain ${POOL_SIZE} unique visible variants`);
  }
}
