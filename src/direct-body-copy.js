function makeStates(cores) {
  if (cores.length !== 20 || STATE_DETAILS.length !== 25) {
    throw new Error("Direct state pool requires 20 physical cores × 25 direct details");
  }
  return cores.flatMap((core) =>
    STATE_DETAILS.map((detail) => `Ти відчуваєш ${core}. ${detail}`)
  );
}

function makeResults(cores) {
  if (cores.length !== 20 || POSITIVE_RESULT_DETAILS.length !== 25) {
    throw new Error("Direct result pool requires 20 physical cores × 25 positive details");
  }
  return cores.flatMap((core) =>
    POSITIVE_RESULT_DETAILS.map((detail) => `${RESULT_PREFIX} ${core}. ${detail}`)
  );
}

export const PRIMARY_BODY_STATES = Object.fromEntries(
  Object.entries(PRIMARY_STATE_CORES).map(([themeKey, cores]) => [themeKey, makeStates(cores)])
);

export const PRIMARY_BODY_RESULTS = Object.fromEntries(
  Object.entries(PRIMARY_RESULT_CORES).map(([themeKey, cores]) => [themeKey, makeResults(cores)])
);

export const GENERIC_DIRECT_STATES = makeStates(GENERIC_STATE_CORES);
export const GENERIC_DIRECT_RESULTS = makeResults(GENERIC_RESULT_CORES);

for (const [name, pool] of Object.entries({
  ...Object.fromEntries(Object.entries(PRIMARY_BODY_STATES).map(([key, value]) => [`state:${key}`, value])),
  ...Object.fromEntries(Object.entries(PRIMARY_BODY_RESULTS).map(([key, value]) => [`result:${key}`, value])),
  genericStates: GENERIC_DIRECT_STATES,
  genericResults: GENERIC_DIRECT_RESULTS
})) {
  if (pool.length !== POOL_SIZE || new Set(pool).size !== POOL_SIZE) {
    throw new Error(`${name} must contain ${POOL_SIZE} unique visible variants`);
  }
}
