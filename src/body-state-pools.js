function combine500(themeKey) {
  const cores = CORES[themeKey] || [];
  const contexts = CONTEXTS[themeKey] || [];
  if (cores.length !== 20 || contexts.length !== 25) {
    throw new Error(`Body-state pool ${themeKey} requires 20 physical cores × 25 contexts`);
  }

  return cores.flatMap((core) =>
    contexts.map((context) => `${PREFIX} ${core}. ${context}`)
  );
}

export const BODY_STATE_POOLS = Object.fromEntries(
  Object.keys(CORES).map((themeKey) => [themeKey, combine500(themeKey)])
);
