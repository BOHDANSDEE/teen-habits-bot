function parts(index) {
  const normalized = ((index % POOL_SIZE) + POOL_SIZE) % POOL_SIZE;
  return {
    baseIndex: normalized % 40,
    firstStyle: Math.floor(normalized / 40) % 10,
    secondStyle: Math.floor(normalized / 400) % 10
  };
}

function buildProblems() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { baseIndex, firstStyle, secondStyle } = parts(index);
    const [behavior, consequence, extra] = PROBLEMS[baseIndex];
    const first = sentence(`${PROBLEM_OPENERS[firstStyle]}${behavior}`);
    const second = sentence(`${PROBLEM_LINKS[secondStyle]}${consequence}`);
    if (index < HALF_POOL) return `${first} ${second}`;
    return `${first} ${second} ${sentence(extra)}`;
  });
}

function buildGains() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { baseIndex, firstStyle, secondStyle } = parts(index);
    const [benefit, why] = GAINS[baseIndex];
    const first = sentence(`${GAIN_OPENERS[firstStyle]}${benefit}`);
    const second = sentence(`Тому тобі вигідно залишатися у такому способі дій ${GAIN_LINKS[secondStyle]}${why}`);
    return `${first} ${second}`;
  });
}

function buildMeanings() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { baseIndex, firstStyle, secondStyle } = parts(index);
    const [area, insight, extra] = MEANINGS[baseIndex];
    const first = sentence(`${MEANING_FRAMES[firstStyle](area, insight)}; ${MEANING_ENDINGS[secondStyle]}`);
    if (index < HALF_POOL) return first;
    return `${first} ${sentence(extra)}`;
  });
}

function buildAffirmations() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { baseIndex, firstStyle, secondStyle } = parts(index);
    const [firstClause, secondClause, thirdClause] = AFFIRMATIONS[baseIndex];
    const first = sentence(`${AFFIRMATION_FIRST[firstStyle]}${firstClause}`);
    const second = sentence(`${AFFIRMATION_SECOND[secondStyle]}${secondClause}`);
    if (index < HALF_POOL) return `${first} ${second}`;
    return `${first} ${second} ${sentence(`Я ${thirdClause}`)}`;
  });
}

function buildResults() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { baseIndex, firstStyle, secondStyle } = parts(index);
    const [alternative, next] = RESULTS[baseIndex];
    const first = sentence(BODY_RELIEF[firstStyle]);
    const second = sentence(`${RESULT_OPENERS[secondStyle]}${alternative}`);
    const third = sentence(`Наступний крок ясніший: ${next}`);
    return `${first} ${second} ${third}`;
  });
}

export const INDEPENDENT_LIFE_POOLS = Object.freeze({
  problems: Object.freeze(buildProblems()),
  gains: Object.freeze(buildGains()),
  meanings: Object.freeze(buildMeanings()),
  affirmations: Object.freeze(buildAffirmations()),
  results: Object.freeze(buildResults())
});

for (const [name, pool] of Object.entries(INDEPENDENT_LIFE_POOLS)) {
  if (pool.length !== POOL_SIZE || new Set(pool).size !== POOL_SIZE) {
    throw new Error(`${name} pool must contain ${POOL_SIZE} unique visible texts`);
  }
}

const randomIndex = () => Math.floor(Math.random() * POOL_SIZE);

export function getIndependentLifeVariant(requestedVariant = null) {
  let problemIndex;
  let gainIndex;
  let meaningIndex;
  let affirmationIndex;
  let resultIndex;

  if (Number.isInteger(requestedVariant)) {
    const base = ((requestedVariant % POOL_SIZE) + POOL_SIZE) % POOL_SIZE;
    problemIndex = base;
    gainIndex = (base * 137 + 59) % POOL_SIZE;
    meaningIndex = (base * 223 + 113) % POOL_SIZE;
    affirmationIndex = (base * 311 + 197) % POOL_SIZE;
    resultIndex = (base * 419 + 271) % POOL_SIZE;
  } else {
    problemIndex = randomIndex();
    gainIndex = randomIndex();
    meaningIndex = randomIndex();
    affirmationIndex = randomIndex();
    resultIndex = randomIndex();
  }

  return {
    problemIndex,
    gainIndex,
    meaningIndex,
    affirmationIndex,
    resultIndex,
    problem: INDEPENDENT_LIFE_POOLS.problems[problemIndex],
    gain: INDEPENDENT_LIFE_POOLS.gains[gainIndex],
    meaning: INDEPENDENT_LIFE_POOLS.meanings[meaningIndex],
    affirmation: INDEPENDENT_LIFE_POOLS.affirmations[affirmationIndex],
    result: INDEPENDENT_LIFE_POOLS.results[resultIndex]
  };
}
