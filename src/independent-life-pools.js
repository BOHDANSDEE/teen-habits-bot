function parts(index) {
  const normalized = ((index % POOL_SIZE) + POOL_SIZE) % POOL_SIZE;
  return {
    scenario: SCENARIOS[normalized % SCENARIOS.length],
    firstStyle: Math.floor(normalized / SCENARIOS.length) % 10,
    secondStyle: Math.floor(normalized / (SCENARIOS.length * 10)) % 10
  };
}

function buildProblems() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { scenario: [problem, effect], firstStyle, secondStyle } = parts(index);
    const first = sentence(`${PROBLEM_OPENERS[firstStyle]}${problem}`);
    const second = sentence(`${EFFECT_OPENERS[secondStyle]}${effect}`);
    if (index < HALF_POOL) return `${first} ${second}`;
    const third = sentence(PROBLEM_THIRDS[(firstStyle + secondStyle) % PROBLEM_THIRDS.length]);
    return `${first} ${second} ${third}`;
  });
}

