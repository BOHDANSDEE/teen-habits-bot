if (AREAS.length * BEHAVIORS.length * LENSES.length !== POOL_SIZE) {
  throw new Error("shared pool seed space must equal POOL_SIZE");
}

function parts(index) {
  const areaIndex = index % AREAS.length;
  const behaviorIndex = Math.floor(index / AREAS.length) % BEHAVIORS.length;
  const lensIndex = Math.floor(index / (AREAS.length * BEHAVIORS.length)) % LENSES.length;
  return { area: AREAS[areaIndex], behavior: BEHAVIORS[behaviorIndex], lens: LENSES[lensIndex], areaIndex, behaviorIndex, lensIndex };
}

