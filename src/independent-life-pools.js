function buildProblems() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const core = PROBLEM_CORES[index % PROBLEM_CORES.length];
    const consequence = PROBLEM_CONSEQUENCES[Math.floor(index / PROBLEM_CORES.length) % PROBLEM_CONSEQUENCES.length];
    const base = `${sentence(core)} ${sentence(consequence)}`;
    if (index < 250) return base;
    return `${base} ${sentence(PROBLEM_THIRDS[(index - 250) % PROBLEM_THIRDS.length])}`;
  });
}

function buildGains() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const benefit = GAIN_BENEFITS[index % GAIN_BENEFITS.length];
    const reason = GAIN_REASONS[Math.floor(index / GAIN_BENEFITS.length) % GAIN_REASONS.length];
    return `${sentence(benefit)} ${sentence(reason)}`;
  });
}

function buildMeanings() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const area = LIFE_AREAS[index % LIFE_AREAS.length];
    const effect = MEANING_EFFECTS[Math.floor(index / LIFE_AREAS.length) % MEANING_EFFECTS.length];
    if (index < 250) {
      return sentence(`У житті це може заважати тобі в ${area}, бо ${effect}`);
    }
    return `${sentence(`У житті це може заважати тобі в ${area}`)} ${sentence(effect.charAt(0).toUpperCase() + effect.slice(1))}`;
  });
}

function buildAffirmations() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const start = AFFIRMATION_STARTS[index % AFFIRMATION_STARTS.length];
    const second = AFFIRMATION_SECONDS[Math.floor(index / AFFIRMATION_STARTS.length) % AFFIRMATION_SECONDS.length];
    const base = `${sentence(start)} ${sentence(second)}`;
    if (index < 250) return base;
    return `${base} ${sentence(AFFIRMATION_THIRDS[(index - 250) % AFFIRMATION_THIRDS.length])}`;
  });
}

function buildResults() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const body = BODY_RELIEF[index % BODY_RELIEF.length];
    const [second, third] = RESULT_ACTIONS[Math.floor(index / BODY_RELIEF.length) % RESULT_ACTIONS.length];
    return `${sentence(body)} ${sentence(second)} ${sentence(third)}`;
  });
}

export const INDEPENDENT_LIFE_POOLS = Object.freeze({
  problems: Object.freeze(buildProblems()),
  gains: Object.freeze(buildGains()),
  meanings: Object.freeze(buildMeanings()),
  affirmations: Object.freeze(buildAffirmations()),
  results: Object.freeze(buildResults())
});

function normalizeIndex(index) {
  const numeric = Number.isInteger(index) ? index : 0;
  return ((numeric % POOL_SIZE) + POOL_SIZE) % POOL_SIZE;
}

const deterministicIndices = (index) => {
  const base = normalizeIndex(index);
  return {
    problemIndex: base,
    gainIndex: (base * 137 + 59) % POOL_SIZE,
    meaningIndex: (base * 223 + 113) % POOL_SIZE,
    affirmationIndex: (base * 311 + 197) % POOL_SIZE,
    resultIndex: (base * 419 + 271) % POOL_SIZE
  };
};

const randomIndex = () => Math.floor(Math.random() * POOL_SIZE);

export function getIndependentLifeVariant(requestedVariant = null) {
  const indices = Number.isInteger(requestedVariant)
    ? deterministicIndices(requestedVariant)
    : {
        problemIndex: randomIndex(),
        gainIndex: randomIndex(),
        meaningIndex: randomIndex(),
        affirmationIndex: randomIndex(),
        resultIndex: randomIndex()
      };

  return {
    ...indices,
    problem: INDEPENDENT_LIFE_POOLS.problems[indices.problemIndex],
    gain: INDEPENDENT_LIFE_POOLS.gains[indices.gainIndex],
    meaning: INDEPENDENT_LIFE_POOLS.meanings[indices.meaningIndex],
    affirmation: INDEPENDENT_LIFE_POOLS.affirmations[indices.affirmationIndex],
    result: INDEPENDENT_LIFE_POOLS.results[indices.resultIndex]
  };
}

for (const [name, pool] of Object.entries(INDEPENDENT_LIFE_POOLS)) {
  if (pool.length !== POOL_SIZE || new Set(pool).size !== POOL_SIZE) {
    throw new Error(`${name}: independent life pool must contain 500 unique visible texts`);
  }
}
