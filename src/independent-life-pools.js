function buildProblems() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { area: [area, focus], behavior: [label, problem, , alternative, next], lens: [moment, , , , actionTail, nextTail], areaIndex, behaviorIndex } = parts(index);
    const lead = PROBLEM_LEADS[(areaIndex + behaviorIndex) % PROBLEM_LEADS.length];
    const first = sentence(`${lead} ${area}, ${problem}; це особливо помітно ${moment}`);
    const second = sentence(`Через повторення «${label}» потрібний крок відсувається, а в темі ${area} стає складніше ${focus}; новий варіант — ${alternative}, ${actionTail}`);
    if (index < HALF_POOL) return `${first} ${second}`;
    const third = sentence(`Так старий спосіб закріплюється швидше, а простий вихід стає менш помітним; у темі ${area} можна повернути вибір через дію: ${next}, ${nextTail}`);
    return `${first} ${second} ${third}`;
  });
}

function buildGains() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { area: [area, focus], behavior: [label, , benefit, alternative], lens: [, , , gainTail, actionTail], lensIndex } = parts(index);
    const first = sentence(`${GAIN_LEADS[lensIndex]} у темі ${area} ця проблема дає коротку користь: можна ${benefit}, ${gainTail}`);
    const second = sentence(`Саме тому тобі вигідно ще трохи залишатися в проблемі «${label}»: знайомий спосіб знижує негайну напругу, хоча пізніше заважає ${focus}; альтернатива — ${alternative}, ${actionTail}`);
    return `${first} ${second}`;
  });
}

function buildMeanings() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { area: [area, focus], behavior: [label, , , alternative], lens: [moment, , , , actionTail], lensIndex } = parts(index);
    const first = sentence(`${MEANING_LEADS[lensIndex]} «${label}» впливає на сферу ${area}, бо заважає ${focus}; особливо це помітно ${moment}`);
    if (index < HALF_POOL) return first;
    const second = sentence(`Коли замість старого способу ти пробуєш ${alternative}, у темі ${area} з’являється більше свободи для власних рішень, ${actionTail}`);
    return `${first} ${second}`;
  });
}

function buildAffirmations() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { area: [area, focus], behavior: [label, , , alternative, next], lens: [, , , , actionTail, nextTail], lensIndex } = parts(index);
    const first = sentence(`${AFFIRM_LEADS[lensIndex]} у темі ${area} замінювати «${label}» на інший спосіб: ${alternative}, ${actionTail}`);
    const second = sentence(`Я підтримую себе конкретною дією — ${next}; так я вчуся ${focus} без вимоги змінити все одразу, ${nextTail}`);
    if (index < HALF_POOL) return `${first} ${second}`;
    const third = sentence(`Я маю право рухатися у своєму темпі й повторювати новий вибір у сфері ${area}, навіть якщо старий спосіб «${label}» іноді повертається, ${actionTail}`);
    return `${first} ${second} ${third}`;
  });
}

function buildResults() {
  return Array.from({ length: POOL_SIZE }, (_, index) => {
    const { area: [area], behavior: [label, , , alternative, next], lens: [, body, relief, , actionTail, nextTail] } = parts(index);
    const first = sentence(`Ти відчуваєш ${relief} ${body}, коли дивишся на «${label}» у сфері ${area} без колишнього тиску; тілу вже не потрібно тримати ту саму напругу`);
    const second = sentence(`Тепер тобі стало легше побачити інший спосіб дії: замість старої реакції у темі ${area} можна ${alternative}, ${actionTail}`);
    const third = sentence(`Тобі стало зрозуміліше, який крок зробити далі: ${next} у сфері ${area}, ${nextTail}`);
    return `${first} ${second} ${third}`;
  });
}

