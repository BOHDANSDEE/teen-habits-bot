function contextFor(themeKey, levelKey) {
  return LEVEL_CONTEXT[`${themeKey}.${levelKey}`] || null;
}

function expand(frames, tags, catalog) {
  const cores = tags.flatMap((tag) => catalog[tag] || []);
  if (frames.length !== 20 || cores.length !== 25) {
    throw new Error("Level context pools require 20 frames and 25 semantic cores");
  }
  return frames.flatMap((frame) => cores.map((core) => `${frame} ${core}`));
}

export function getProblemFact(themeKey, levelKey) {
  return contextFor(themeKey, levelKey)?.problemFact || "";
}

export function getLevelSecondaryGainPool(themeKey, levelKey) {
  const context = contextFor(themeKey, levelKey);
  return context ? expand(GAIN_FRAMES, context.gainTags, GAIN_MECHANISMS) : [];
}

export function getLevelLifeMeaningPool(themeKey, levelKey) {
  const context = contextFor(themeKey, levelKey);
  return context ? expand(LIFE_FRAMES, context.lifeTags, LIFE_IMPACTS) : [];
}
