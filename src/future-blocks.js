const makeLevel = (blockKey, themeKey, index, title, firstSlug = null) => ({
  name: `${index + 1} · ${title}`,
  articleTitle: title,
  articleSlug: firstSlug && index === 0 ? firstSlug : `${blockKey}-${themeKey}-${index + 1}`,
  summary: `Розбір теми «${title}» простими словами й один наступний крок.`,
  state: "",
  problem: "",
  secondaryGain: "",
  meaning: "",
  actions: [],
  affirmation: "",
  note: ""
});

const makeSubtheme = (blockKey, themeKey, name, description, titles, firstSlug) => ({
  name,
  description,
  levels: Object.fromEntries(
    titles.map((title, index) => [
      `r${index + 1}`,
      makeLevel(blockKey, themeKey, index, title, firstSlug)
    ])
  )
});

