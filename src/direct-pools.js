function stripCore(raw = "", prefix = "") {
  const value = String(raw || "").trim();
  return value.startsWith(prefix) ? value.slice(prefix.length).trim() : value;
}

function personalizeCore(text = "") {
  return String(text || "")
    .replace(/після паузи людина вимагає від себе/gu, "після паузи ти вимагаєш від себе")
    .replace(/людина перестає робити/gu, "ти перестаєш робити")
    .replace(/після зриву людина карає себе/gu, "після зриву ти караєш себе")
    .replace(/людина вчиться/gu, "ти вчишся")
    .replace(/цей рівень/giu, "ця ситуація")
    .replace(/цього рівня/giu, "цієї ситуації")
    .replace(/цим рівнем/giu, "цією ситуацією")
    .replace(/може бути/gu, "є")
    .replace(/можуть бути/gu, "є")
    .replace(/може проявлятися/gu, "проявляється")
    .replace(/можуть проявлятися/gu, "проявляються")
    .replace(/може впливати/gu, "впливає")
    .replace(/можуть впливати/gu, "впливають")
    .replace(/може допомагати/gu, "допомагає")
    .replace(/може допомогти/gu, "допомагає")
    .replace(/може давати/gu, "дає")
    .replace(/може знижувати/gu, "знижує")
    .replace(/може посилювати/gu, "посилює")
    .replace(/може ставати/gu, "стає")
    .replace(/може виникати/gu, "виникає")
    .replace(/може з’являтися/gu, "з’являється")
    .replace(/може повертатися/gu, "повертається")
    .replace(/може триматися/gu, "тримається")
    .replace(/може переходити/gu, "переходить")
    .replace(/може залишатися/gu, "залишається")
    .replace(/може здаватися/gu, "здається")
    .replace(/може відчуватися/gu, "відчувається")
    .replace(/може вимагати/gu, "вимагає")
    .replace(/може забирати/gu, "забирає")
    .trim();
}

function getCores(rawPool = [], sectionKey) {
  const prefix = CORE_PREFIXES[sectionKey];
  return rawPool.slice(0, 25).map((item) => personalizeCore(stripCore(item, prefix)));
}

function combineDirect(frames = [], cores = []) {
  if (frames.length !== 20 || cores.length !== 25) {
    throw new Error("Direct pools require 20 frames and 25 semantic cores");
  }
  return frames.flatMap((frame) => cores.map((core) => `${frame} ${core}`));
}

function rewriteTheme(rawTheme = {}) {
  return Object.fromEntries(
    Object.keys(DIRECT_FRAMES).map((sectionKey) => [
      sectionKey,
      combineDirect(DIRECT_FRAMES[sectionKey], getCores(rawTheme[sectionKey], sectionKey))
    ])
  );
}

export const THEME_POOLS = Object.fromEntries(
  Object.entries(RAW_THEME_POOLS).map(([themeKey, rawTheme]) => [themeKey, rewriteTheme(rawTheme)])
);
