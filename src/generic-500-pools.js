const sentence = (text = "") => {
  const value = String(text || "").trim().replace(/[.!?…]+$/u, "");
  return value ? `${value}.` : "";
};
const lowerFirst = (text = "") => {
  const value = String(text || "").trim().replace(/[.!?…]+$/u, "");
  return value ? `${value.charAt(0).toLocaleLowerCase("uk-UA")}${value.slice(1)}` : "";
};
const firstSentence = (text = "", fallback = "") => {
  const raw = String(text || fallback).trim();
  return raw.split(/(?<=[.!?…])\s+/u).filter(Boolean)[0]?.replace(/[.!?…]+$/u, "") || fallback;
};

