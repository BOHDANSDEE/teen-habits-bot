function topicContext(template, topic) {
  return sentence(String(template).replaceAll("{topic}", topic));
}

function makeBodyStates(topic) {
  return make500(BODY_SENSATIONS, BODY_CONTEXTS, (sensation, context) =>
    `Ти відчуваєш ${sensation}. ${topicContext(context, topic)}`
  );
}

function makeResults() {
  return make500(BODY_RELIEFS, RESULT_CONTEXTS, (relief, context) =>
    `Тепер ти відчуваєш, ${relief}. ${sentence(context)}`
  );
}

export const GENERIC_BODY_STATES = makeBodyStates("ця ситуація");
export const GENERIC_RESULTS = makeResults();

export function buildGenericPools(level = {}) {
  const topic = cleanTopic(level);
  const problemCore = firstSentence(level.problem, "потрібний крок залишається нечітким");
  const gainCore = firstSentence(level.secondaryGain, "на короткий час стає легше нічого не змінювати");
  const meaningCore = firstSentence(level.meaning, "ця тема впливає на щоденні рішення");

  return {
    states: makeBodyStates(topic),
    problems: make500(PROBLEM_STARTS, PROBLEM_ENDS, (start, end) =>
      `${start} ${problemCore} ${sentence(end)}`
    ),
    gains: make500(GAIN_STARTS, GAIN_ENDS, (start, end) =>
      `${start} ${gainCore} ${sentence(end)}`
    ),
    meanings: make500(MEANING_STARTS, MEANING_ENDS, (start, end) =>
      `${start} ${meaningCore} ${sentence(end)}`
    ),
    solutions: make500(SOLUTION_STARTS, SOLUTION_ENDS, (start, end) =>
      `${sentence(start)} ${sentence(end)}`
    ),
    results: GENERIC_RESULTS
  };
}
