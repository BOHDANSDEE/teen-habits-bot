const sentence = (text = "") => {
  const value = String(text || "").trim().replace(/[.!?…]+$/u, "");
  return value ? `${value}.` : "";
};

const firstSentence = (text = "", fallback = "") => {
  const raw = String(text || fallback).trim();
  return sentence(raw.split(/(?<=[.!?…])\s+/u).filter(Boolean)[0] || fallback);
};

const cleanTopic = (level = {}) =>
  String(level.name || level.articleTitle || "ця ситуація")
    .replace(/^\d+\s*·\s*/u, "")
    .replace(/[.!?…]+$/u, "")
    .trim() || "ця ситуація";

const make500 = (left, right, build) => {
  if (left.length !== 20 || right.length !== 25) {
    throw new Error("500-pool requires 20 × 25 source variants");
  }
  return left.flatMap((a, i) => right.map((b, j) => build(a, b, i * 25 + j)));
};

