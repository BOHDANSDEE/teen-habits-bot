function areaFor(level = {}) {
  const topic = `${level.name || ""} ${level.articleTitle || ""}`.toLocaleLowerCase("uk-UA");
  if (/сон|режим/u.test(topic)) return "сон, ранок і рівень енергії";
  if (/енерг|ресурс|виснаж/u.test(topic)) return "енергію, навантаження і щоденні плани";
  if (/рух|спорт|трен/u.test(topic)) return "рух, самопочуття і регулярність";
  if (/впевнен|самооцін|знецін/u.test(topic)) return "самооцінку, рішення і спілкування";
  if (/ціл|дисципл/u.test(topic)) return "цілі, завершення справ і довіру до себе";
  if (/звич/u.test(topic)) return "звички, послідовність і щоденний ритм";
  if (/спілк|стосунк|меж/u.test(topic)) return "спілкування, межі й близькі стосунки";
  if (/навчан|вчит|школ/u.test(topic)) return "навчання, увагу і дедлайни";
  if (/робот|кар'єр|кар’єр/u.test(topic)) return "роботу, кар'єрні рішення і концентрацію";
  if (/телефон|екран|віде/u.test(topic)) return "увагу, час і здатність завершувати справи";
  if (/прибиран|побут|простір/u.test(topic)) return "домашній простір, увагу і щоденні справи";
  return "щоденні рішення, час і відчуття контролю";
}

export function buildGenericPools(level = {}) {
  if (level && typeof level === "object" && genericPoolCache.has(level)) return genericPoolCache.get(level);
  const topic = cleanLevelName(level.name || level.articleTitle);
  const problemCore = firstSentence(level.problem, `Ти стикаєшся з проблемою «${topic}»`);
  const gainCore = firstSentence(level.secondaryGain, "старий спосіб дає коротке полегшення");
  const area = areaFor(level);

  const problems = [];
  for (const link of PROBLEM_LINKS) {
    for (const end of PROBLEM_ENDS) problems.push(`${sentence(problemCore)} ${sentence(`${link} ${end}`)}`);
  }
  for (const link of PROBLEM_LINKS) {
    for (let j = 0; j < PROBLEM_ENDS.length; j += 1) {
      problems.push(`${sentence(problemCore)} ${sentence(`${link} ${PROBLEM_ENDS[j]}`)} ${sentence(PROBLEM_THIRDS[j])}`);
    }
  }

  const gains = GAIN_FRAMES.flatMap((frame) =>
    GAIN_SECONDS.map((ending) =>
      `${sentence(frame.replaceAll("{gain}", lowerFirst(gainCore)))} ${sentence(ending)}`
    )
  );

  const meanings = [];
  for (const frame of MEANING_ONE) {
    for (const tail of MEANING_TAILS) {
      meanings.push(sentence(`${frame.replaceAll("{topic}", topic).replaceAll("{area}", area)} ${tail}`));
    }
  }
  for (let i = 0; i < MEANING_ONE.length; i += 1) {
    for (let j = 0; j < MEANING_TAILS.length; j += 1) {
      meanings.push(`${sentence(`${MEANING_ONE[i].replaceAll("{topic}", topic).replaceAll("{area}", area)} ${MEANING_TAILS[j]}`)} ${sentence(MEANING_SECONDS[j])}`);
    }
  }

  const affirmations = buildLevelAffirmationPool(level);
  const results = buildLevelResultPool(level);
  const pools = { problems, gains, meanings, affirmations, results };
  for (const [name, pool] of Object.entries(pools)) {
    if (pool.length !== 500 || new Set(pool).size !== 500) {
      throw new Error(`${topic}/${name}: pool must have 500 unique visible variants`);
    }
  }
  if (level && typeof level === "object") genericPoolCache.set(level, pools);
  return pools;
}
