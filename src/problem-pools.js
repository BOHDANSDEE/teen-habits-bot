function lowerFirst(text = "") {
  const value = String(text || "").trim().replace(/[.!?…]+$/u, "");
  if (!value) return "ця проблема повторюється";
  return `${value.charAt(0).toLocaleLowerCase("uk-UA")}${value.slice(1)}`;
}

export function getLevelProblemPool(themeKey, levelKey) {
  const fact = lowerFirst(getProblemFact(themeKey, levelKey));
  if (FRAMES.length !== 20 || CONSEQUENCES.length !== 25) {
    throw new Error("Problem pool requires 20 frames × 25 consequences");
  }

  return FRAMES.flatMap((frame) =>
    CONSEQUENCES.map((consequence) => `${frame} ${fact}. ${consequence}`)
  );
}
