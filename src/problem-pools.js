const problemCache = new Map();

const sentence = (text = "") => {
  const value = String(text || "").trim().replace(/[.!?…]+$/u, "");
  return value ? `${value}.` : "";
};

export function getLevelProblemPool(themeKey, levelKey) {
  const cacheKey = `${themeKey}.${levelKey}`;
  if (problemCache.has(cacheKey)) return problemCache.get(cacheKey);
  const fact = sentence(getProblemFact(themeKey, levelKey) || "Ти повторюєш дію, яка не дає потрібного результату");
  if (LINKS.length !== 10 || CONSEQUENCES.length !== 25 || THIRD_SENTENCES.length !== 25) {
    throw new Error("Problem pool requires 10 links × 25 consequences × two sentence modes");
  }

  const twoSentence = LINKS.flatMap((link) =>
    CONSEQUENCES.map((consequence) => `${fact} ${sentence(`${link} ${consequence}`)}`)
  );
  const threeSentence = LINKS.flatMap((link) =>
    CONSEQUENCES.map((consequence, index) =>
      `${fact} ${sentence(`${link} ${consequence}`)} ${sentence(THIRD_SENTENCES[index])}`
    )
  );
  const pool = [...twoSentence, ...threeSentence];
  if (pool.length !== 500 || new Set(pool).size !== 500) {
    throw new Error(`${themeKey}/${levelKey}: problem pool must have 500 unique visible texts`);
  }
  problemCache.set(cacheKey, pool);
  return pool;
}
