function combine100(left, right) {
  if (left.length !== 10 || right.length !== 10) {
    throw new Error("Each pool seed list must contain exactly 10 items");
  }

  return left.flatMap((a) => right.map((b) => `${a} ${b}`));
}

function makePools(endings) {
  return {
    states: combine100(SHARED.statesLeft, endings.statesRight),
    problems: combine100(SHARED.problemsLeft, endings.problemsRight),
    secondaryGains: combine100(SHARED.secondaryLeft, endings.secondaryRight),
    meanings: combine100(SHARED.meaningsLeft, endings.meaningsRight),
    affirmations: combine100(SHARED.affirmLeft, endings.affirmRight)
  };
}

export const THEME_POOLS = Object.fromEntries(
  Object.entries(THEME_ENDINGS).map(([themeKey, endings]) => [themeKey, makePools(endings)])
);
