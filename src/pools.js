function combine500(starts, endings) {
  if (starts.length !== 20 || endings.length !== 25) {
    throw new Error("Each content pool must use 20 frames and 25 theme cores");
  }

  return starts.flatMap((start) => endings.map((ending) => `${start} ${ending}`));
}

function makePools(themeCores) {
  return {
    states: combine500(FRAMES.states, themeCores.states),
    problems: combine500(FRAMES.problems, themeCores.problems),
    secondaryGains: combine500(FRAMES.secondaryGains, themeCores.secondaryGains),
    meanings: combine500(FRAMES.meanings, themeCores.meanings),
    affirmations: combine500(FRAMES.affirmations, themeCores.affirmations)
  };
}

export const THEME_POOLS = Object.fromEntries(
  Object.entries(THEME_CORES).map(([themeKey, themeCores]) => [themeKey, makePools(themeCores)])
);
