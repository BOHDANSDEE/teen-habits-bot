const affirmationCache = new WeakMap();
const resultCache = new WeakMap();

function assert500(name, pool) {
  if (pool.length !== OUTPUT_POOL_SIZE || new Set(pool).size !== OUTPUT_POOL_SIZE) {
    throw new Error(`${name} must contain ${OUTPUT_POOL_SIZE} unique visible variants`);
  }
}

export function buildLevelAffirmationPool(level = {}) {
  if (level && typeof level === "object" && affirmationCache.has(level)) return affirmationCache.get(level);
  const target = cleanSummary(level.summary);
  const pool = [];
  for (const first of AFFIRMATION_FIRSTS) {
    for (const action of AFFIRMATION_ACTIONS) {
      pool.push(`${sentence(first)} ${sentence(replace(action, { target }))}`);
    }
  }
  for (let i = 0; i < AFFIRMATION_FIRSTS.length; i += 1) {
    for (let j = 0; j < AFFIRMATION_ACTIONS.length; j += 1) {
      pool.push(`${sentence(AFFIRMATION_FIRSTS[i])} ${sentence(replace(AFFIRMATION_ACTIONS[j], { target }))} ${sentence(AFFIRMATION_THIRDS[j])}`);
    }
  }
  assert500("affirmations", pool);
  if (level && typeof level === "object") affirmationCache.set(level, pool);
  return pool;
}

export function buildLevelResultPool(level = {}) {
  if (level && typeof level === "object" && resultCache.has(level)) return resultCache.get(level);
  const name = cleanLevelName(level.name || level.articleTitle);
  const target = cleanSummary(level.summary);
  const pool = RESULT_FIRSTS.flatMap((first) =>
    RESULT_SECONDS.map((second) =>
      `${sentence(replace(first, { name }))} ${sentence(replace(second, { target }))}`
    )
  );
  assert500("results", pool);
  if (level && typeof level === "object") resultCache.set(level, pool);
  return pool;
}

export function buildNextPreview(nextLevel = {}, variantIndex = 0) {
  const title = cleanLevelName(nextLevel.name || nextLevel.articleTitle);
  const target = cleanSummary(nextLevel.summary);
  const index = Number.isInteger(variantIndex)
    ? ((variantIndex % OUTPUT_POOL_SIZE) + OUTPUT_POOL_SIZE) % OUTPUT_POOL_SIZE
    : Math.floor(Math.random() * OUTPUT_POOL_SIZE);
  const first = NEXT_FIRSTS[Math.floor(index / 25)] || NEXT_FIRSTS[0];
  const second = NEXT_SECONDS[index % 25] || NEXT_SECONDS[0];
  return {
    title,
    text: `${sentence(replace(first, { target }))} ${sentence(second)}`
  };
}
