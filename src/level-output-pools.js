export const OUTPUT_POOL_SIZE = 500;

const stripEnd = (text = "") => String(text || "").trim().replace(/[.!?…]+$/u, "");
const sentence = (text = "") => {
  const value = stripEnd(text);
  return value ? `${value}.` : "";
};
const replace = (template, values) =>
  Object.entries(values).reduce(
    (value, [key, replacement]) => value.replaceAll(`{${key}}`, replacement),
    template
  );

export const cleanLevelName = (name = "") =>
  String(name || "").replace(/^\d+\s*·\s*/u, "").trim() || "Ця проблема";

const cleanSummary = (summary = "") =>
  stripEnd(String(summary || "").replace(/^Фокус\s*—\s*/u, "")) ||
  "зробити один зрозумілий наступний крок";

