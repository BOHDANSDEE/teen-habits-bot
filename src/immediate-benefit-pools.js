function combine500(cores) {
  if (FRAMES.length !== 20 || cores.length !== 25) throw new Error("Immediate-benefit pools require 20 frames × 25 cores");
  return FRAMES.flatMap((frame) => cores.map((core) => `${frame} ${core}`));
}

export const IMMEDIATE_BENEFIT_POOLS = Object.fromEntries(
  Object.entries(CORES).map(([themeKey, cores]) => [themeKey, combine500(cores)])
);
