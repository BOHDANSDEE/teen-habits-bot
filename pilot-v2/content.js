function pick(items, rng = Math.random) {
  if (!Array.isArray(items) || items.length === 0) {
    throw new Error("Cannot pick from an empty content pool");
  }

  const index = Math.min(items.length - 1, Math.floor(rng() * items.length));
  return items[index];
}

export function getSubtheme(subthemeKey) {
  return PILOT_THEME.subthemes[subthemeKey] || null;
}

export function getLevel(subthemeKey, levelKey) {
  return getSubtheme(subthemeKey)?.levels?.[levelKey] || null;
}

export function getFirstLevel(subthemeKey) {
  const subtheme = getSubtheme(subthemeKey);
  if (!subtheme) return null;
  return Object.values(subtheme.levels)[0] || null;
}

export function buildResult(subthemeKey, { rng = Math.random } = {}) {
  const subtheme = getSubtheme(subthemeKey);

  if (!subtheme) {
    throw new Error(`Unknown subtheme: ${subthemeKey}`);
  }

  const pools = subtheme.pools;

  const parts = {
    intro: pick(pools.intro, rng),
    state: pick(pools.state, rng),
    problem: pick(pools.problem, rng),
    secondaryGain: pick(pools.secondaryGain, rng),
    meaning: pick(pools.meaning, rng),
    affirmation: pick(pools.affirmation, rng)
  };

  const safety =
    subthemeKey === "apathy"
      ? "\n\nℹ️ Це не діагностика. Якщо низька енергія та втрата інтересу тривають тижнями, сильно заважають навчанню чи повсякденному життю або з'являються думки про самоушкодження — потрібна допомога дорослого та фахівця."
      : "";

  return {
    subthemeKey,
    title: subtheme.name,
    parts,
    text: `💭 Ти так це відчуваєш?\n\n${parts.intro}\n\n🔹 Стан\n${parts.state}\n\n🔹 Проблема\n${parts.problem}\n\n🔹 Вторинна вигода\n${parts.secondaryGain}\n\n🔹 Значення в житті\n${parts.meaning}\n\n🔹 Афірмація\n«${parts.affirmation}»${safety}`
  };
}

export function pickNextSubtheme(currentSubthemeKey, { rng = Math.random } = {}) {
  const available = Object.keys(PILOT_THEME.subthemes).filter(
    (key) => key !== currentSubthemeKey
  );

  if (!available.length) return null;
  return pick(available, rng);
}

