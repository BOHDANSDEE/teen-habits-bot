async function sendLessonContent(chatId, lesson) {
  const content = lesson.content;

  if (!content) {
    await bot.sendMessage(chatId, "🎬 Матеріал уроку скоро буде.");
    return;
  }

if (content.type === "placeholder") {
  await bot.sendMessage(
    chatId,
    `🎬 Відео уроку

${content.value}

Після перегляду відео натисни кнопку нижче і пройди короткий тест із 4 питань.`,
    {
      reply_markup: afterVideoKeyboard(lesson.id)
    }
  );
  return;
}

  if (content.type === "youtube") {
    await bot.sendMessage(
      chatId,
      `🎬 Відео уроку:

${content.value}`
    );
    return;
  }

  if (content.type === "telegram_video") {
    await bot.sendVideo(chatId, content.value, {
      caption: "🎬 Відео уроку"
    });
    return;
  }

  if (content.type === "text") {
    await bot.sendMessage(
      chatId,
      `📖 Текстовий урок:

${content.value}`
    );
    return;
  }

  await bot.sendMessage(chatId, "🎬 Матеріал уроку скоро буде.");
}

